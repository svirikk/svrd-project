// server/config.js
//
// Фіксовані параметри продукту. Ці значення НЕ залежать від конкретного
// фото — клієнт отримує фізичну раму з ФІКСОВАНОЮ кількістю цвяхів, тож
// num_pins / skipped_neighbors / scale_factor завжди однакові для всіх
// замовлень (див. обговорення: "залізо" продукту не можна підлаштовувати
// під кожне фото окремо, інакше рами будуть несумісні).
//
// Єдине, що адаптивно змінюється під конкретне фото — це предобробка фону
// в convert.py (адаптивне спрощення заднього плану залежно від його
// "складності"), а НЕ параметри C++ рушія.
//
// Пояснення MIN_STEPS / MAX_STEPS: бізнесу потрібна консистентна кількість
// ниток (~3800-4000) для будь-якого фото — стільки фізично можна сплести
// на рамі. C++ рушій тепер примусово домотує до MIN_STEPS, навіть якщо
// картинка вже "зійшлася" раніше, і ніколи не перевищує MAX_STEPS.
//
// Пояснення THRESHOLD: завдяки жорсткому вікну MIN_STEPS..MAX_STEPS точне
// значення threshold майже не впливає на фінальну кількість ліній — воно
// лише вирішує, чи зупинитись РАНІШЕ за MAX_STEPS, якщо картинка вже повністю
// "зійшлася" ще до MIN_STEPS. Для більшості фото природна збіжність настає
// раніше (~3000-3300 ліній), тож більшість замовлень вийдуть рівно на 4000.

const path = require('path');

const ROOT_DIR = path.join(__dirname, '..');

module.exports = {
  // --- "залізо" продукту (рама 50x50 см, 240 цвяхів) ---
  NUM_PINS: 240,
  SKIPPED_NEIGHBORS: 27,
  SCALE_FACTOR: 4,              // фінальне полотно = 1024 * 4 = 4096x4096
  IMAGE_SIZE: 1024,             // роздільність, яку розуміють convert.py і C++ рушій

  // Реальний діаметр кола, на якому розташовані піни (НЕ діаметр рами —
  // трохи менше за 50см, щоб лишити поле рамки). Наближене значення;
  // якщо реальний вимір відрізняється — поправити тут, застосунок
  // складання порахує довжину нитки саме за цим числом.
  PIN_CIRCLE_DIAMETER_CM: 48,

  // --- бізнес-вимога: 3800-4000 ниток на роботу ---
  MIN_STEPS: 3800,
  MAX_STEPS: 4000,
  THRESHOLD: 2.0,                // майже не впливає завдяки MIN_STEPS, див. коментар вище
  DRAFT_OPACITY_CLI_ARG: 0.1,    // позиційний аргумент; C++ рушій все одно перераховує його сам

  // --- шляхи до скриптів/бінарника/робочих папок ---
  PYTHON_BIN: process.env.PYTHON_BIN || 'python3',
  CONVERT_SCRIPT: path.join(ROOT_DIR, 'convert.py'),
  STRING_ART_BIN: path.join(ROOT_DIR, 'bin', 'string-art'),
  TMP_DIR: path.join(ROOT_DIR, 'tmp'),
  PUBLIC_DIR: path.join(ROOT_DIR, 'public'),

  // --- постійне сховище замовлень (піни для застосунку складання) ---
  // ВАЖЛИВО: на Railway (і більшості контейнерних платформ) локальний диск
  // НЕ переживає редеплой, якщо не підключити Volume саме на цей шлях.
  // Без Volume кожен `git push` / redeploy стирає всі замовлення й прогрес
  // складання клієнтів. Див. README.
  DATA_DIR: process.env.DATA_DIR || path.join(ROOT_DIR, 'data'),
  get ORDERS_DIR() {
    return path.join(this.DATA_DIR, 'orders');
  },

  // --- rate limiting для входу за кодом замовлення ---
  ASSEMBLY_RATE_LIMIT_WINDOW_MS: 15 * 60 * 1000,
  ASSEMBLY_RATE_LIMIT_MAX: 20, // спроб на IP за вікно (захист від підбору коду)

  // Синхронізація прогресу (POST .../progress) — це рутинний фоновий трафік
  // під час активного складання (автоплей раз на 1-10с × кожні 15 кроків),
  // а не спроба входу. При швидкості 1с/крок повний набір ~3800 кроків дає
  // ~250 синхронізацій за ~63 хв — тому ліміт тут набагато вищий за
  // ASSEMBLY_RATE_LIMIT_MAX, інакше автоплей сам себе заблокує.
  ASSEMBLY_PROGRESS_RATE_LIMIT_MAX: 300,

  // Через скільки днів ПІСЛЯ завершення складання (крок дійшов до кінця)
  // видаляти запис замовлення з data/orders/. НЕ впливає на незавершені
  // замовлення — вони зберігаються без обмеження за часом, скільки б людина
  // не робила паузу. Головна причина видалення — не місце на диску (один
  // запис ~14 КБ, тисячі замовлень — лічені мегабайти), а гігієна даних:
  // не тримати вічно ПІБ/адресу/телефон клієнта після завершення угоди.
  ORDER_RETENTION_DAYS_AFTER_COMPLETION: 10,

  // --- ліміти на завантажене фото ---
  MAX_UPLOAD_MB: 15,
  ALLOWED_MIME: ['image/jpeg', 'image/png', 'image/webp'],

  // --- скільки часу даємо на одну генерацію, перш ніж вважати що щось зависло ---
  GENERATION_TIMEOUT_MS: 90_000,

  // --- сервер ---
  PORT: process.env.PORT || 3000,

  // --- Telegram-бот (заповнюється у .env, див. .env.example) ---
  TELEGRAM_BOT_TOKEN: process.env.TELEGRAM_BOT_TOKEN || '',
  TELEGRAM_CHAT_ID: process.env.TELEGRAM_CHAT_ID || '',
};
